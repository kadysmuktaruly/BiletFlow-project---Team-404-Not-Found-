"""/organizer: the signed-in organizer's profile, payout account and events (SRS 4.1, 4.2)."""

import uuid

from fastapi import APIRouter, status

from app.deps import CurrentOrganizer, OrganizerUser, OwnedEvent, SessionDep
from app.errors import AppError, error_responses
from app.models import Event, OrganizerProfile, PayoutAccount
from app.schemas.event import (
    CancelEventRequest,
    EventCreate,
    EventRead,
    EventUpdate,
    PublicEventRead,
)
from app.schemas.organizer import (
    OrganizerProfileRead,
    OrganizerProfileUpdate,
    PayoutAccountRead,
    PayoutAccountUpsert,
)
from app.schemas.staff import StaffAssign, StaffRead
from app.schemas.ticket_type import TicketTypeCreate, TicketTypeRead, TicketTypeUpdate
from app.services import events as event_service
from app.services import organizer as organizer_service
from app.services import staff as staff_service
from app.services import ticket_types as ticket_type_service

router = APIRouter(prefix="/organizer", tags=["organizer"], responses=error_responses(401, 403))


@router.get("/profile", response_model=OrganizerProfileRead, summary="Your organizer profile")
async def read_profile(organizer: CurrentOrganizer, session: SessionDep) -> OrganizerProfile:
    await session.commit()  # persists a lazily created profile
    return organizer


@router.put("/profile", response_model=OrganizerProfileRead, summary="Update contact details")
async def update_profile(
    data: OrganizerProfileUpdate, organizer: CurrentOrganizer, session: SessionDep
) -> OrganizerProfile:
    return await organizer_service.update_profile(session, organizer, data)


@router.get(
    "/payout-account",
    response_model=PayoutAccountRead,
    responses=error_responses(404),
    summary="Your simulated payout account (DEMO)",
)
async def read_payout_account(organizer: CurrentOrganizer, session: SessionDep) -> PayoutAccount:
    account = await organizer_service.get_payout_account(session, organizer)
    if account is None:
        raise AppError(404, "payout_account_not_found", "No payout account yet.")
    return account


@router.put(
    "/payout-account",
    response_model=PayoutAccountRead,
    summary="Set up the simulated payout account (DEMO)",
    description=(
        "Send only the last four digits of the account number. Verification is simulated "
        "and immediate; no real identity or bank checks happen (SRS 8)."
    ),
)
async def upsert_payout_account(
    data: PayoutAccountUpsert, organizer: CurrentOrganizer, session: SessionDep
) -> PayoutAccount:
    return await organizer_service.upsert_payout_account(session, organizer, data)


@router.post(
    "/events",
    response_model=EventRead,
    status_code=status.HTTP_201_CREATED,
    summary="Create a draft event",
    description=(
        "Times without a UTC offset are read as local time in `timezone` (an IANA name). "
        "The slug is generated by the server."
    ),
)
async def create_event(
    data: EventCreate, organizer: CurrentOrganizer, session: SessionDep
) -> Event:
    return await event_service.create_draft(session, organizer, data)


@router.get("/events", response_model=list[EventRead], summary="Your events, newest first")
async def list_events(organizer: CurrentOrganizer, session: SessionDep) -> list[Event]:
    return await event_service.list_owned(session, organizer)


@router.get(
    "/events/{event_id}",
    response_model=EventRead,
    responses=error_responses(404),
    summary="One of your events",
)
async def read_event(event: OwnedEvent) -> Event:
    return event


@router.patch(
    "/events/{event_id}",
    response_model=EventRead,
    responses=error_responses(404, 409),
    summary="Edit an event",
)
async def update_event(
    data: EventUpdate, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> Event:
    return await event_service.update(session, event, user, data)


@router.post(
    "/events/{event_id}/publish",
    response_model=EventRead,
    responses=error_responses(404, 409),
    summary="Publish an event",
    description=(
        "Needs a verified email, a venue, at least one visible ticket type, and an end time "
        "in the future. Public events then appear in the listing; unlisted ones open by link."
    ),
)
async def publish_event(event: OwnedEvent, user: OrganizerUser, session: SessionDep) -> Event:
    return await event_service.publish(session, event, user)


@router.post(
    "/events/{event_id}/unpublish",
    response_model=EventRead,
    responses=error_responses(404, 409),
    summary="Unpublish an event: hide its page and stop new registrations",
    description="Tickets already issued stay valid.",
)
async def unpublish_event(event: OwnedEvent, user: OrganizerUser, session: SessionDep) -> Event:
    return await event_service.unpublish(session, event, user)


@router.post(
    "/events/{event_id}/cancel",
    response_model=EventRead,
    responses=error_responses(404, 409),
    summary="Cancel an event",
    description=(
        "Cancels every valid ticket (they fail at check-in) and releases unpaid orders. "
        "Refunds for paid orders arrive with SRS 4.9."
    ),
)
async def cancel_event(
    data: CancelEventRequest, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> Event:
    return await event_service.cancel(session, event, user, data.reason)


@router.get(
    "/events/{event_id}/preview",
    response_model=PublicEventRead,
    responses=error_responses(404),
    summary="Preview the public page, whatever the event's status",
)
async def preview_event(event: OwnedEvent, session: SessionDep) -> PublicEventRead:
    return await event_service.public_read(session, event, preview=True)


# --- staff (SRS 4.8) ------------------------------------------------------------------------


@router.get(
    "/events/{event_id}/staff",
    response_model=list[StaffRead],
    responses=error_responses(404),
    summary="People who can check attendees in at this event",
)
async def list_staff(event: OwnedEvent, session: SessionDep) -> list[StaffRead]:
    return await staff_service.list_staff(session, event)


@router.post(
    "/events/{event_id}/staff",
    response_model=StaffRead,
    status_code=status.HTTP_201_CREATED,
    responses=error_responses(404, 409),
    summary="Assign an existing user as Event Admin or check-in staff",
    description="Event admins can scan and undo check-ins; check-in staff can only scan.",
)
async def assign_staff(
    data: StaffAssign, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> StaffRead:
    return await staff_service.assign(session, event, user, data)


@router.delete(
    "/events/{event_id}/staff/{assignment_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    responses=error_responses(404),
    summary="Remove someone from the event's staff",
)
async def revoke_staff(
    assignment_id: uuid.UUID, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> None:
    await staff_service.revoke(session, event, user, assignment_id)


# --- ticket types (SRS 4.3) ---------------------------------------------------------------


@router.get(
    "/events/{event_id}/ticket-types",
    response_model=list[TicketTypeRead],
    responses=error_responses(404),
    summary="Ticket types with available, reserved, sold, refunded and checked-in counts",
)
async def list_ticket_types(event: OwnedEvent, session: SessionDep) -> list[TicketTypeRead]:
    types = await ticket_type_service.list_for_event(session, event)
    return await ticket_type_service.to_read(session, types)


@router.post(
    "/events/{event_id}/ticket-types",
    response_model=TicketTypeRead,
    status_code=status.HTTP_201_CREATED,
    responses=error_responses(404, 409),
    summary="Add a free (price 0) or paid ticket type",
    description="Sales-window times without a UTC offset are read in the event's time zone.",
)
async def create_ticket_type(
    data: TicketTypeCreate, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> TicketTypeRead:
    tt = await ticket_type_service.create(session, event, user, data)
    return (await ticket_type_service.to_read(session, [tt]))[0]


@router.patch(
    "/events/{event_id}/ticket-types/{ticket_type_id}",
    response_model=TicketTypeRead,
    responses=error_responses(404, 409),
    summary="Edit a ticket type, or hide it with is_hidden",
)
async def update_ticket_type(
    ticket_type_id: uuid.UUID,
    data: TicketTypeUpdate,
    event: OwnedEvent,
    user: OrganizerUser,
    session: SessionDep,
) -> TicketTypeRead:
    tt = await ticket_type_service.get_for_event(session, event, ticket_type_id)
    tt = await ticket_type_service.update(session, event, tt, user, data)
    return (await ticket_type_service.to_read(session, [tt]))[0]


@router.delete(
    "/events/{event_id}/ticket-types/{ticket_type_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    responses=error_responses(404, 409),
    summary="Delete a ticket type that has never been ordered",
)
async def delete_ticket_type(
    ticket_type_id: uuid.UUID, event: OwnedEvent, user: OrganizerUser, session: SessionDep
) -> None:
    tt = await ticket_type_service.get_for_event(session, event, ticket_type_id)
    await ticket_type_service.delete(session, event, tt, user)
