"""/organizer: the signed-in organizer's profile, payout account and events (SRS 4.1, 4.2)."""

from fastapi import APIRouter, status

from app.deps import CurrentOrganizer, OwnedEvent, SessionDep
from app.errors import AppError, error_responses
from app.models import Event, OrganizerProfile, PayoutAccount
from app.schemas.event import EventCreate, EventRead, EventUpdate
from app.schemas.organizer import (
    OrganizerProfileRead,
    OrganizerProfileUpdate,
    PayoutAccountRead,
    PayoutAccountUpsert,
)
from app.services import events as event_service
from app.services import organizer as organizer_service

router = APIRouter(prefix="/organizer", tags=["organizer"], responses=error_responses(401, 403))


@router.get("/profile", response_model=OrganizerProfileRead, summary="Your organizer profile")
async def read_profile(organizer: CurrentOrganizer, session: SessionDep) -> OrganizerProfile:
    await session.commit()  # persists a lazily created profile
    return organizer


@router.put("/profile", response_model=OrganizerProfileRead, summary="Update contact details")
async def update_profile(
    data: OrganizerProfileUpdate, organizer: CurrentOrganizer, session: SessionDep
) -> OrganizerProfile:
    return await organizer_service.update_profile(session, organizer, data)


@router.get(
    "/payout-account",
    response_model=PayoutAccountRead,
    responses=error_responses(404),
    summary="Your simulated payout account (DEMO)",
)
async def read_payout_account(organizer: CurrentOrganizer, session: SessionDep) -> PayoutAccount:
    account = await organizer_service.get_payout_account(session, organizer)
    if account is None:
        raise AppError(404, "payout_account_not_found", "No payout account yet.")
    return account


@router.put(
    "/payout-account",
    response_model=PayoutAccountRead,
    summary="Set up the simulated payout account (DEMO)",
    description=(
        "Send only the last four digits of the account number. Verification is simulated "
        "and immediate; no real identity or bank checks happen (SRS 8)."
    ),
)
async def upsert_payout_account(
    data: PayoutAccountUpsert, organizer: CurrentOrganizer, session: SessionDep
) -> PayoutAccount:
    return await organizer_service.upsert_payout_account(session, organizer, data)


@router.post(
    "/events",
    response_model=EventRead,
    status_code=status.HTTP_201_CREATED,
    summary="Create a draft event",
    description=(
        "Times without a UTC offset are read as local time in `timezone` (an IANA name). "
        "The slug is generated by the server."
    ),
)
async def create_event(
    data: EventCreate, organizer: CurrentOrganizer, session: SessionDep
) -> Event:
    return await event_service.create_draft(session, organizer, data)


@router.get("/events", response_model=list[EventRead], summary="Your events, newest first")
async def list_events(organizer: CurrentOrganizer, session: SessionDep) -> list[Event]:
    return await event_service.list_owned(session, organizer)


@router.get(
    "/events/{event_id}",
    response_model=EventRead,
    responses=error_responses(404),
    summary="One of your events",
)
async def read_event(event: OwnedEvent) -> Event:
    return event


@router.patch(
    "/events/{event_id}",
    response_model=EventRead,
    responses=error_responses(404, 409),
    summary="Edit an event",
)
async def update_event(data: EventUpdate, event: OwnedEvent, session: SessionDep) -> Event:
    return await event_service.update(session, event, data)
